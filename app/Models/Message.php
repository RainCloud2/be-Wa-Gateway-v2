<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class Message extends Model
{
    use HasFactory;

    public const SENDER_EMPLOYEE = 'employee';

    public const SENDER_AI = 'ai';

    public const SENDER_TECH = 'tech';

    public const SENDER_SYSTEM = 'system';

    public const DELIVERY_PENDING = 'pending';

    public const DELIVERY_SENT = 'sent';

    public const DELIVERY_FAILED = 'failed';

    protected $fillable = [
        'session_id',
        'ticket_id',
        'sender',
        'body',
        'media_type',
        'wa_message_id',
        'delivery_status',
        'read_at',
    ];

    protected function casts(): array
    {
        return [
            'read_at' => 'datetime',
        ];
    }

    /**
     * True when this message is generated by our side and must be delivered
     * to the employee through the WhatsApp driver.
     */
    public function isOutgoing(): bool
    {
        return in_array($this->sender, [self::SENDER_AI, self::SENDER_TECH, self::SENDER_SYSTEM], true);
    }

    /** @return BelongsTo<ChatSession, $this> */
    public function session(): BelongsTo
    {
        return $this->belongsTo(ChatSession::class, 'session_id');
    }

    /** @return BelongsTo<Ticket, $this> */
    public function ticket(): BelongsTo
    {
        return $this->belongsTo(Ticket::class);
    }
}
