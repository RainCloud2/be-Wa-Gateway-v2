        document.addEventListener('notify', function(e) {
            var detail = e.detail;
            if (typeof $.notify === 'function') {
                $.notify({
                    title: detail.title || (detail.type === 'success' ? 'Success' : detail.type === 'danger' ? 'Error' : detail.type === 'warning' ? 'Warning' : 'Info'),
                    message: detail.message,
                    icon: detail.type === 'success' ? 'fa fa-check-circle' : detail.type === 'danger' ? 'fa fa-times-circle' : detail.type === 'warning' ? 'fa fa-exclamation-triangle' : 'fa fa-info-circle',
                }, {
                    type: detail.type === 'danger' ? 'danger' : detail.type || 'info',
                    placement: {
                        from: 'bottom',
                        align: 'right'
                    },
                    time: 3000,
                });
            }
        });
